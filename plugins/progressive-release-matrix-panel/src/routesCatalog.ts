export interface RouteCategoryGroup {
  key: string;
  name: string;
  enName: string;
  type: 'frontend' | 'api';
  items: CatalogItem[];
  totalCount: number;
  passCount: number;
  failCount: number;
}

export interface RouteRootGroup {
  type: 'frontend' | 'api';
  title: string;
  enTitle: string;
  categories: RouteCategoryGroup[];
  totalCount: number;
  passCount: number;
  failCount: number;
}

/**
 * 将平铺清单聚合为前端/后端三级树状结构
 */
export function buildRoutesTree(items: CatalogItem[]): RouteRootGroup[] {
  const feItems = items.filter((i) => i.type === 'frontend');
  const beItems = items.filter((i) => i.type === 'api');

  const groupByCategory = (list: CatalogItem[], rootType: 'frontend' | 'api'): RouteCategoryGroup[] => {
    const map = new Map<string, CatalogItem[]>();
    for (const item of list) {
      if (!map.has(item.categoryKey)) {
        map.set(item.categoryKey, []);
      }
      map.get(item.categoryKey)!.push(item);
    }

    const groups: RouteCategoryGroup[] = [];
    map.forEach((catItems, key) => {
      const first = catItems[0];
      const passCount = catItems.filter((i) => i.result === 'PASS').length;
      const failCount = catItems.filter((i) => i.result === 'FAIL').length;
      groups.push({
        key,
        name: first.categoryName,
        enName: first.categoryEnName,
        type: rootType,
        items: catItems,
        totalCount: catItems.length,
        passCount,
        failCount,
      });
    });

    return groups;
  };

  const feGroups = groupByCategory(feItems, 'frontend');
  const beGroups = groupByCategory(beItems, 'api');

  return [
    {
      type: 'frontend',
      title: '前端页面路由',
      enTitle: 'Frontend Pages & Routes',
      categories: feGroups,
      totalCount: feItems.length,
      passCount: feItems.filter((i) => i.result === 'PASS').length,
      failCount: feItems.filter((i) => i.result === 'FAIL').length,
    },
    {
      type: 'api',
      title: '后端服务与 API 接口',
      enTitle: 'Backend Services & APIs',
      categories: beGroups,
      totalCount: beItems.length,
      passCount: beItems.filter((i) => i.result === 'PASS').length,
      failCount: beItems.filter((i) => i.result === 'FAIL').length,
    },
  ];
}
