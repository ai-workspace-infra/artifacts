#!/usr/bin/env python3
"""Sync the canonical workload-autoscaling helper into every chart.

Canonical source: oci/charts/library/workload-autoscaling/templates/_autoscaling.tpl
For each chart with its own workload templates this writes:
  templates/_autoscaling.tpl   identical copy of the canonical helper (generated)
  templates/autoscaling.yaml   one include listing the chart's workload templates (generated)
Charts built on web-saas-common get the helper from that library and only need
autoscaling.yaml. Use --check in CI to fail when a copy drifts.
"""
import re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LIB = ROOT / "oci/charts/open-platform/library/workload-autoscaling"
CANON = (LIB / "templates/_autoscaling.tpl").read_text()
WEBSAAS_COMMON = ROOT / "oci/charts/web-saas-fullstack/subcharts/web-saas-common"
WORKLOAD = re.compile(r"^kind:\s*(Deployment|StatefulSet|DaemonSet)\b|websaas\.fleet", re.M)
HEADER = "{{- /* Generated by scripts/sync_autoscaling_helper.py; do not edit. */ -}}\n"

def charts():
    for chart_yaml in sorted((ROOT / "oci").rglob("Chart.yaml")):
        d = chart_yaml.parent
        if d == LIB or LIB in d.parents:
            continue
        if re.search(r"^type:\s*library", chart_yaml.read_text(), re.M):
            continue
        tdir = d / "templates"
        if not tdir.is_dir():
            continue
        files = sorted(p.name for p in tdir.glob("*.yaml")
                       if p.name != "autoscaling.yaml" and WORKLOAD.search(p.read_text()))
        if files:
            yield d, files, (d.parent / "web-saas-common") == WEBSAAS_COMMON

def expected():
    out = {WEBSAAS_COMMON / "templates/_autoscaling.tpl": CANON}
    for d, files, websaas in charts():
        if not websaas:
            out[d / "templates/_autoscaling.tpl"] = CANON
        lst = " ".join(f'"{f}"' for f in files)
        out[d / "templates/autoscaling.yaml"] = HEADER + '{{- include "workload-autoscaling.render" (dict "root" . "files" (list ' + lst + ')) }}\n'
    return out

def main():
    check = "--check" in sys.argv
    drift = []
    for path, content in expected().items():
        if not path.exists() or path.read_text() != content:
            drift.append(path.relative_to(ROOT))
            if not check:
                path.write_text(content)
    if check and drift:
        print("autoscaling helper drift:", *drift, sep="\n  "); sys.exit(1)
    print(("checked" if check else "synced"), len(expected()), "files;", len(drift), "changed")

if __name__ == "__main__":
    main()
